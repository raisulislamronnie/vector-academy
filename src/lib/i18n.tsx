const DICTS: Record<Lang, Record<string, string>> = { en: {}, bn: BN };

type Ctx = { lang: Lang; setLang: (l: Lang) => void; t: (s: string, vars?: Record<string, string | number>) => string };

const BN_DIGITS = "০১২৩৪৫৬৭৮৯";
/** Western digits to Bangla digits. */
export const bnNum = (v: string | number) => String(v).replace(/\d/g, (d) => BN_DIGITS[Number(d)]);

function translate(lang: Lang, s: string, vars?: Record<string, string | number>) {
  let out = DICTS[lang][s] ?? s;
  if (vars)
    for (const [k, v] of Object.entries(vars)) out = out.replaceAll(`{${k}}`, lang === "bn" && (typeof v === "number" || /^[\d.:/]+$/.test(v)) ? bnNum(v) : String(v));
  return out;
}

const LangContext = createContext<Ctx>({ lang: "en", setLang: () => {}, t: (s, v) => translate("en", s, v) });

export function LangProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>("en");
  useEffect(() => {
    try {
      if (localStorage.getItem(LANG_KEY) === "bn") setLangState("bn");
    } catch {}
  }, []);
  useEffect(() => {
    document.documentElement.lang = lang;
  }, [lang]);
  const setLang = useCallback((l: Lang) => {
    setLangState(l);
    try {
      localStorage.setItem(LANG_KEY, l);
    } catch {}
  }, []);
  const t = useCallback((s: string, vars?: Record<string, string | number>) => translate(lang, s, vars), [lang]);
  return <LangContext.Provider value={{ lang, setLang, t }}>{children}</LangContext.Provider>;
}

export const useI18n = () => useContext(LangContext);
